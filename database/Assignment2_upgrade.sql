BEGIN;
CREATE TABLE IF NOT EXISTS "SystemAccount" (
 "AccountID" SERIAL PRIMARY KEY,
 "FullName" VARCHAR(100) NOT NULL,
 "Email" VARCHAR(254) NOT NULL UNIQUE CHECK ("Email" = lower(trim("Email"))),
 "PasswordHash" TEXT NOT NULL,
 "Role" SMALLINT NOT NULL DEFAULT 0 CHECK ("Role" IN (0,1)),
 "CreatedDate" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 "SessionVersion" INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS "RefreshToken" (
 "RefreshTokenID" UUID PRIMARY KEY,
 "AccountID" INTEGER NOT NULL REFERENCES "SystemAccount"("AccountID") ON DELETE CASCADE,
 "TokenHash" VARCHAR(64) NOT NULL UNIQUE,
 "FamilyID" UUID NOT NULL,
 "CreatedDate" TIMESTAMPTZ NOT NULL,
 "ExpiresDate" TIMESTAMPTZ NOT NULL,
 "RevokedDate" TIMESTAMPTZ NULL,
 "ReplacedByID" UUID NULL
);
CREATE INDEX IF NOT EXISTS "IX_RefreshToken_AccountID" ON "RefreshToken"("AccountID");
CREATE INDEX IF NOT EXISTS "IX_RefreshToken_FamilyID" ON "RefreshToken"("FamilyID");
ALTER TABLE "Task" ADD COLUMN IF NOT EXISTS "CreatedByID" INTEGER REFERENCES "SystemAccount"("AccountID") ON DELETE RESTRICT;
ALTER TABLE "Task" ADD COLUMN IF NOT EXISTS "UpdatedByID" INTEGER REFERENCES "SystemAccount"("AccountID") ON DELETE SET NULL;
ALTER TABLE "Project" ADD COLUMN IF NOT EXISTS "CreatedByID" INTEGER REFERENCES "SystemAccount"("AccountID") ON DELETE SET NULL;
ALTER TABLE "Project" ADD COLUMN IF NOT EXISTS "UpdatedByID" INTEGER REFERENCES "SystemAccount"("AccountID") ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS "IX_Task_CreatedByID" ON "Task"("CreatedByID");
COMMIT;
